#!/usr/bin/env python3
"""Copy Tellomi's DC and RSA settings into a telegram-ios checkout.

The committed source is tellomi/server/tellomi-server.json. A normal Xcode
build runs this script first and patches the pinned submodule in the working
tree. The gitlink SHA does not change.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import shutil
import subprocess
import sys
import tempfile
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
JSON_PATH = ROOT / "tellomi" / "server" / "tellomi-server.json"
HEADER_PATH = ROOT / "tellomi" / "mtproto" / "TellomiServerConfigJSON.h"
OVERLAY = ROOT / "tellomi" / "mtproto"
IOS_PIN = "fb0e62ba8a147f0821da6aa63c09da7d79a10111"
UPSTREAM_BASE = f"https://raw.githubusercontent.com/TelegramMessenger/Telegram-iOS/{IOS_PIN}"
PRODUCTION_HOST = "8.137.39.82"
PRODUCTION_PORT = 10443
# 11443 is the stated staging port. It is not a seed until that switch is confirmed.
STAGING_PORT_UNCONFIRMED = 11443

DEFAULT_PUBLIC_KEYS = """\
static NSArray<MTDatacenterAuthPublicKey *> *defaultPublicKeys(bool isProduction) {
    NSMutableArray<MTDatacenterAuthPublicKey *> *keys = [[NSMutableArray alloc] init];
    for (NSString *pem in TellomiServerPublicKeys(isProduction)) {
        [keys addObject:[[MTDatacenterAuthPublicKey alloc] initWithPublicKey:pem]];
    }
    return keys;
}
"""

FINGERPRINT_SWAP = """\
/// Teamgram's gnetway does not compute this fingerprint. It sends the decimal
/// from gnetway.yaml, which is SHA1[12:20] read little-endian. `MTRsaFingerprint`
/// reads those same eight bytes big-endian. Either value selects the same key.
static uint64_t MTDatacenterAuthFingerprintByteSwap(uint64_t fingerprint) {
    return ((fingerprint & 0x00000000000000ffULL) << 56) |
        ((fingerprint & 0x000000000000ff00ULL) << 40) |
        ((fingerprint & 0x0000000000ff0000ULL) << 24) |
        ((fingerprint & 0x00000000ff000000ULL) << 8) |
        ((fingerprint & 0x000000ff00000000ULL) >> 8) |
        ((fingerprint & 0x0000ff0000000000ULL) >> 24) |
        ((fingerprint & 0x00ff000000000000ULL) >> 40) |
        ((fingerprint & 0xff00000000000000ULL) >> 56);
}
"""

SELECT_PUBLIC_KEY = """\
static MTDatacenterAuthPublicKey *selectPublicKey(id<EncryptionProvider> encryptionProvider, NSArray<NSNumber *> *fingerprints, NSArray<MTDatacenterAuthPublicKey *> *publicKeys, uint64_t *announcedFingerprint) {
    NSMutableArray<NSNumber *> *keyFingerprints = [[NSMutableArray alloc] init];
    for (MTDatacenterAuthPublicKey *key in publicKeys) {
        [keyFingerprints addObject:@([key fingerprintWithEncryptionProvider:encryptionProvider])];
    }

    // Exact match first, so a Telegram fingerprint (big-endian) still wins
    // over a coincidental byte-swap of a different key.
    for (int pass = 0; pass < 2; pass++) {
        for (NSNumber *nFingerprint in fingerprints) {
            uint64_t remote = [nFingerprint unsignedLongLongValue];
            for (NSUInteger i = 0; i < publicKeys.count; i++) {
                uint64_t local = [keyFingerprints[i] unsignedLongLongValue];
                bool matches = pass == 0 ? remote == local : remote == MTDatacenterAuthFingerprintByteSwap(local);
                if (matches) {
                    if (announcedFingerprint != NULL) {
                        // Echo the value the server announced. Teamgram looks the
                        // key up by the decimal in gnetway.yaml, not by the
                        // big-endian fingerprint this client computes.
                        *announcedFingerprint = remote;
                    }
                    return publicKeys[i];
                }
            }
        }
    }

    return nil;
}
"""


def load_config() -> dict:
    return json.loads(JSON_PATH.read_text(encoding="utf-8"))


def canonical_json(obj: dict) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=True) + "\n"


def objc_string_literal(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        else:
            out.append(ch)
    return "".join(out)


def header_text(json_text: str) -> str:
    literal = objc_string_literal(json_text)
    return (
        "// Generated by tellomi/apply_mtproto.py from tellomi/server/tellomi-server.json.\n"
        "// Do not edit. Change the JSON, then rerun python3 tellomi/apply_mtproto.py --generate.\n"
        f'#define TELLOMI_SERVER_CONFIG_JSON @"{literal}"\n'
    )


def generate() -> None:
    json_text = JSON_PATH.read_text(encoding="utf-8")
    obj = json.loads(json_text)
    canonical = canonical_json(obj)
    if json_text != canonical:
        JSON_PATH.write_text(canonical, encoding="utf-8")
        json_text = canonical
    HEADER_PATH.write_text(header_text(json_text), encoding="utf-8")


def tl_bytes(data: bytes) -> bytes:
    size = len(data)
    if size < 254:
        out = bytes([size]) + data
    else:
        out = bytes([254]) + size.to_bytes(3, "little") + data
    if len(out) % 4:
        out += b"\x00" * (4 - (len(out) % 4))
    return out


def pkcs1_modulus_exponent(pem: str) -> tuple[bytes, bytes]:
    with tempfile.TemporaryDirectory() as directory:
        path = pathlib.Path(directory) / "key.pem"
        path.write_text(pem if pem.endswith("\n") else pem + "\n", encoding="utf-8")
        text = subprocess.check_output(
            ["openssl", "rsa", "-pubin", "-inform", "PEM", "-RSAPublicKey_in", "-in", str(path), "-text", "-noout"],
            text=True,
        )
    modulus = bytearray()
    in_modulus = False
    exponent = None
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("Modulus:"):
            in_modulus = True
            continue
        if stripped.startswith("Exponent:"):
            in_modulus = False
            exponent = int(stripped.split()[1])
            continue
        if in_modulus:
            for part in stripped.split(":"):
                if part:
                    modulus.append(int(part, 16))
    if not modulus or exponent is None:
        raise RuntimeError("could not parse PKCS#1 public key")
    if modulus[0] == 0:
        modulus = modulus[1:]
    return bytes(modulus), exponent.to_bytes((exponent.bit_length() + 7) // 8, "big")


def fingerprints(pem: str) -> tuple[int, int]:
    modulus, exponent = pkcs1_modulus_exponent(pem)
    digest = hashlib.sha1(tl_bytes(modulus) + tl_bytes(exponent)).digest()
    piece = digest[12:20]
    return int.from_bytes(piece, "little"), int.from_bytes(piece, "big")


def validate_config(obj: dict) -> list[str]:
    problems = []
    if obj.get("seed_port") != PRODUCTION_PORT:
        problems.append("seed_port is not the production MTProto port 10443")
    if obj.get("seed_port") == STAGING_PORT_UNCONFIRMED:
        problems.append("staging port 11443 is not confirmed and must not be dialed")
    if obj.get("disable_telegram_backup_discovery") is not True:
        problems.append("Telegram backup discovery is not disabled")
    for environment in ("production", "testing"):
        seeds = obj.get("seeds", {}).get(environment, {})
        for datacenter in ("1", "2"):
            hosts = seeds.get(datacenter)
            if hosts != [PRODUCTION_HOST]:
                problems.append(f"{environment} dc {datacenter} is not the production IP literal")
        for hosts in seeds.values():
            for host in hosts:
                if any(ch.isalpha() for ch in host):
                    problems.append(f"{environment} seed contains a hostname")
    recorded = obj.get("rsa_fingerprints") or []
    for environment in ("production", "testing"):
        pems = obj.get("public_keys", {}).get(environment) or []
        if len(pems) != 2:
            problems.append(f"{environment} does not have two public keys")
            continue
        computed = [fingerprints(pem) for pem in pems]
        if environment == "production":
            if len(recorded) != len(computed):
                problems.append("rsa_fingerprints count does not match the production keys")
            else:
                for index, ((little, big), item) in enumerate(zip(computed, recorded)):
                    if str(little) != str(item.get("little_endian")) or str(big) != str(item.get("big_endian")):
                        problems.append(f"production key {index} fingerprint does not match the JSON")
        if environment == "testing":
            production = [fingerprints(pem) for pem in obj["public_keys"]["production"]]
            if computed != production:
                problems.append("testing keys differ from production keys")
    return problems


def replace_c_function(text: str, signature: str, replacement: str) -> str:
    start = text.find(signature)
    if start < 0:
        if replacement.strip() in text:
            return text
        raise RuntimeError("missing function " + signature.split("(", 1)[0])
    brace = text.find("{", start)
    depth = 0
    for index in range(brace, len(text)):
        char = text[index]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                end = index + 1
                break
    else:
        raise RuntimeError("unbalanced function " + signature)
    current = text[start:end]
    if current.strip() == replacement.strip():
        return text
    return text[:start] + replacement.rstrip() + "\n" + text[end:]


def patch_network(text: str) -> str:
    if "TellomiSeedAddresses" not in text:
        start = text.find("            let seedAddressList: [Int: [String]]\n")
        end_mark = "port: 443, preferForMedia: false, restrictToTcp: false, cdn: false, preferForProxy: false, secret: nil) }))\n            }\n"
        end_at = text.find(end_mark, start)
        if start < 0 or end_at < 0:
            raise RuntimeError("Telegram seed block was not found in Network.swift")
        end = end_at + len(end_mark)
        text = (
            text[:start]
            + "            // Hosts, port and the RSA key live in tellomi/server/tellomi-server.json.\n"
            + "            let seedPort = TellomiSeedPort()\n"
            + "            for (id, ips) in TellomiSeedAddresses(testingEnvironment) {\n"
            + "                context.setSeedAddressSetForDatacenterWithId(id.intValue, seedAddressSet: MTDatacenterAddressSet(addressList: ips.map { MTDatacenterAddress(ip: $0, port: seedPort, preferForMedia: false, restrictToTcp: false, cdn: false, preferForProxy: false, secret: nil) }))\n"
            + "            }\n"
            + text[end:]
        )
    if "TellomiDisablesTelegramBackupDiscovery" not in text:
        old = "            if !supplementary {\n                context.setDiscoverBackupAddressListSignal("
        new = "            if !supplementary {\n                if !TellomiDisablesTelegramBackupDiscovery() {\n                    context.setDiscoverBackupAddressListSignal("
        if old not in text:
            raise RuntimeError("backup discovery call was not found in Network.swift")
        text = text.replace(old, new, 1)
        call = "context.setDiscoverBackupAddressListSignal(MTBackupAddressSignals.fetchBackupIps(testingEnvironment, currentContext: context, additionalSource: wrappedAdditionalSource, phoneNumber: phoneNumber, mainDatacenterId: datacenterId))\n"
        if call not in text:
            raise RuntimeError("backup discovery call changed shape")
        text = text.replace(call, call + "                }\n", 1)
    telegram_seed = "149." + "154."
    if telegram_seed in text:
        raise RuntimeError("patched Network.swift still contains a Telegram datacenter address")
    return text


def patch_auth(text: str) -> str:
    import_line = "#import <MtProtoKit/TellomiServerConfig.h>\n"
    if import_line not in text:
        anchor = '#import "MTSetClientDhParamsResponseMessage.h"\n'
        if anchor not in text:
            raise RuntimeError("auth message service import anchor missing")
        text = text.replace(anchor, anchor + "\n" + import_line, 1)
    text = replace_c_function(
        text,
        "static NSArray<MTDatacenterAuthPublicKey *> *defaultPublicKeys(bool isProduction)",
        DEFAULT_PUBLIC_KEYS,
    )
    if "MTDatacenterAuthFingerprintByteSwap" not in text:
        text = text.replace(DEFAULT_PUBLIC_KEYS, DEFAULT_PUBLIC_KEYS + "\n" + FINGERPRINT_SWAP, 1)
    text = replace_c_function(
        text,
        "static MTDatacenterAuthPublicKey *selectPublicKey(id<EncryptionProvider> encryptionProvider, NSArray<NSNumber *> *fingerprints, NSArray<MTDatacenterAuthPublicKey *> *publicKeys",
        SELECT_PUBLIC_KEY,
    )
    old_call = "MTDatacenterAuthPublicKey *publicKey = selectPublicKey(_encryptionProvider, resPqMessage.serverPublicKeyFingerprints, _publicKeys);"
    new_call = "uint64_t announcedFingerprint = 0;\n            MTDatacenterAuthPublicKey *publicKey = selectPublicKey(_encryptionProvider, resPqMessage.serverPublicKeyFingerprints, _publicKeys, &announcedFingerprint);"
    if old_call in text:
        text = text.replace(old_call, new_call, 1)
    elif "announcedFingerprint" not in text:
        raise RuntimeError("selectPublicKey call site was not found")
    fallback = "                publicKey = _publicKeys[0];\n"
    announced = "                announcedFingerprint = [resPqMessage.serverPublicKeyFingerprints[0] unsignedLongLongValue];\n"
    if fallback in text and announced not in text:
        text = text.replace(fallback, fallback + announced, 1)
    old_fp = "                _dhPublicKeyFingerprint = [publicKey fingerprintWithEncryptionProvider:_encryptionProvider];\n"
    new_fp = (
        "                if (announcedFingerprint != 0) {\n"
        "                    _dhPublicKeyFingerprint = (int64_t)announcedFingerprint;\n"
        "                } else {\n"
        "                    _dhPublicKeyFingerprint = [publicKey fingerprintWithEncryptionProvider:_encryptionProvider];\n"
        "                }\n"
    )
    if old_fp in text:
        text = text.replace(old_fp, new_fp, 1)
    if "BEGIN RSA PUBLIC KEY" in text:
        raise RuntimeError("patched auth service still embeds an RSA key")
    if "TellomiServerPublicKeys" not in text or "MTDatacenterAuthFingerprintByteSwap" not in text:
        raise RuntimeError("patched auth service does not use the Tellomi key and fingerprint")
    return text


def patch_umbrella(text: str) -> str:
    line = "#import <MtProtoKit/TellomiServerConfig.h>\n"
    if line in text:
        return text
    if not text.endswith("\n"):
        text += "\n"
    return text + line


def copy_overlay(ios_root: pathlib.Path) -> None:
    mapping = {
        OVERLAY / "TellomiServerConfig.h": ios_root / "submodules/MtProtoKit/PublicHeaders/MtProtoKit/TellomiServerConfig.h",
        OVERLAY / "TellomiServerConfig.m": ios_root / "submodules/MtProtoKit/Sources/TellomiServerConfig.m",
        HEADER_PATH: ios_root / "submodules/MtProtoKit/Sources/TellomiServerConfigJSON.h",
    }
    for source, destination in mapping.items():
        if not source.is_file():
            raise RuntimeError(f"missing {source}")
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)


def refusal_gaps(obj: dict) -> list[str]:
    """Abnormal configs must be rejected. These samples are not written and are not dialed."""
    gaps = []
    samples = []
    hostname = json.loads(json.dumps(obj))
    hostname["seeds"]["production"]["1"] = ["api.tellomi.cn"]
    samples.append(("hostname", hostname))
    staging = json.loads(json.dumps(obj))
    staging["seed_port"] = STAGING_PORT_UNCONFIRMED
    samples.append(("staging-port", staging))
    empty_keys = json.loads(json.dumps(obj))
    empty_keys["public_keys"]["production"] = []
    empty_keys["public_keys"]["testing"] = []
    samples.append(("empty-rsa", empty_keys))
    missing_seed = json.loads(json.dumps(obj))
    missing_seed["seeds"] = {"production": {}, "testing": {}}
    samples.append(("missing-seed", missing_seed))
    for name, sample in samples:
        if not validate_config(sample):
            gaps.append(f"abnormal config {name} was accepted")
    return gaps


def patch_tree(ios_root: pathlib.Path) -> None:
    problems = validate_config(load_config())
    if problems:
        raise RuntimeError("refusing to apply abnormal MTProto config: " + "; ".join(problems))
    generate()
    required = [
        ios_root / "submodules/TelegramCore/Sources/Network/Network.swift",
        ios_root / "submodules/MtProtoKit/Sources/MTDatacenterAuthMessageService.m",
        ios_root / "submodules/MtProtoKit/PublicHeaders/MtProtoKit/MtProtoKit.h",
    ]
    missing = [path for path in required if not path.is_file()]
    if missing:
        raise RuntimeError("telegram-ios checkout is missing " + ", ".join(str(path.relative_to(ios_root)) for path in missing))
    copy_overlay(ios_root)
    replacements = [
        (required[0], patch_network),
        (required[1], patch_auth),
        (required[2], patch_umbrella),
    ]
    for path, patch in replacements:
        path.write_text(patch(path.read_text(encoding="utf-8")), encoding="utf-8")


def tree_is_patched(ios_root: pathlib.Path) -> bool:
    network = ios_root / "submodules/TelegramCore/Sources/Network/Network.swift"
    auth = ios_root / "submodules/MtProtoKit/Sources/MTDatacenterAuthMessageService.m"
    umbrella = ios_root / "submodules/MtProtoKit/PublicHeaders/MtProtoKit/MtProtoKit.h"
    header = ios_root / "submodules/MtProtoKit/Sources/TellomiServerConfigJSON.h"
    if not all(path.is_file() for path in (network, auth, umbrella, header)):
        return False
    network_text = network.read_text(encoding="utf-8")
    auth_text = auth.read_text(encoding="utf-8")
    return (
        "TellomiSeedAddresses" in network_text
        and ("149." + "154.") not in network_text
        and "TellomiDisablesTelegramBackupDiscovery" in network_text
        and "BEGIN RSA PUBLIC KEY" not in auth_text
        and "TellomiServerPublicKeys" in auth_text
        and "TellomiServerConfig.h" in umbrella.read_text(encoding="utf-8")
        and header.read_text(encoding="utf-8") == HEADER_PATH.read_text(encoding="utf-8")
    )


def submodule_root() -> pathlib.Path:
    return ROOT / "submodules" / "telegram-ios"


def download_upstream(destination: pathlib.Path) -> None:
    files = {
        "submodules/TelegramCore/Sources/Network/Network.swift": destination / "submodules/TelegramCore/Sources/Network/Network.swift",
        "submodules/MtProtoKit/Sources/MTDatacenterAuthMessageService.m": destination / "submodules/MtProtoKit/Sources/MTDatacenterAuthMessageService.m",
        "submodules/MtProtoKit/PublicHeaders/MtProtoKit/MtProtoKit.h": destination / "submodules/MtProtoKit/PublicHeaders/MtProtoKit/MtProtoKit.h",
    }
    for relative, path in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        url = UPSTREAM_BASE + "/" + relative
        try:
            with urllib.request.urlopen(url, timeout=60) as response:
                path.write_bytes(response.read())
        except Exception as error:
            raise RuntimeError(f"could not download {relative}: {error}") from error


def self_test() -> int:
    generate()
    obj = load_config()
    problems = validate_config(obj)
    if JSON_PATH.read_text(encoding="utf-8") != canonical_json(obj):
        problems.append("tellomi-server.json is not canonical")
    if HEADER_PATH.read_text(encoding="utf-8") != header_text(JSON_PATH.read_text(encoding="utf-8")):
        problems.append("generated header does not match the JSON")
    embedded = HEADER_PATH.read_text(encoding="utf-8")
    if PRODUCTION_HOST not in embedded or ("149." + "154.") in embedded:
        problems.append("generated header does not contain the production seed")
    if obj.get("seed_port") == STAGING_PORT_UNCONFIRMED:
        problems.append("configured seed port is the unconfirmed staging port")
    problems.extend(refusal_gaps(obj))
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    print("tellomi mtproto config ok")
    return 0


def check_upstream() -> int:
    status = self_test()
    if status != 0:
        return status
    with tempfile.TemporaryDirectory() as directory:
        ios_root = pathlib.Path(directory)
        download_upstream(ios_root)
        patch_tree(ios_root)
        if not tree_is_patched(ios_root):
            print("upstream pin did not accept the MTProto patch", file=sys.stderr)
            return 1
        # Applying twice must leave the tree patched and not raise.
        patch_tree(ios_root)
        if not tree_is_patched(ios_root):
            print("second apply did not stay patched", file=sys.stderr)
            return 1
    print(f"tellomi mtproto patch applies to {IOS_PIN}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--generate", action="store_true", help="rewrite the generated header from the JSON")
    parser.add_argument("--self-test", action="store_true", help="check the JSON, header and fingerprints")
    parser.add_argument("--check-upstream", action="store_true", help="patch a temporary copy of the pinned telegram-ios files")
    parser.add_argument("--check", action="store_true", help="require the local submodule checkout to already be patched")
    args = parser.parse_args()
    try:
        if args.generate:
            generate()
            print(f"wrote {HEADER_PATH.relative_to(ROOT)}")
            return 0
        if args.self_test:
            return self_test()
        if args.check_upstream:
            return check_upstream()
        ios_root = submodule_root()
        if args.check:
            generate()
            if tree_is_patched(ios_root):
                print("tellomi mtproto patch is applied")
                return 0
            print("tellomi mtproto patch is not applied; run python3 tellomi/apply_mtproto.py", file=sys.stderr)
            return 1
        patch_tree(ios_root)
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print("error: " + str(error), file=sys.stderr)
        return 1
    print("applied tellomi mtproto config to submodules/telegram-ios")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
